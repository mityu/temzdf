//! Compiles the vendored libtexprintf (see vendor/libtexprintf/README.md)
//! into a static library: no pkg-config, no autotools. Upstream's
//! `gen_errorflags.sh` (a shell script) writes `errorflags.h` and
//! `errormessages.h` from comments in the sources; the same is done here
//! in Rust, into `OUT_DIR`.

use std::fmt::Write as _;
use std::path::PathBuf;

const DIR: &str = "vendor/libtexprintf";
/// Library sources, without upstream's `main.c` and `testfonts.c`.
const SOURCES: &[&str] = &["boxes.c", "drawbox.c", "texprintf.c", "parser.c", "lexer.c", "error.c", "stringutils.c"];
/// The files scanned for `// ERRORFLAG NAME "message"`, in the order of
/// upstream's `src/Makefile.am` (the flag numbers follow it).
const FLAG_SOURCES: &[&str] = &["boxes.c", "drawbox.c", "lexer.c", "parser.c"];

fn main() {
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    let mut flags = String::from("/* Generated by build.rs, do not edit by hand */\n");
    let mut messages = String::from("/* Generated by build.rs, do not edit by hand */\nchar *EMessages[] = {\n");
    let mut n = 0;
    for file in FLAG_SOURCES {
        let text = std::fs::read_to_string(format!("{DIR}/{file}")).expect("read libtexprintf");
        for line in text.lines() {
            let Some(at) = line.find("// ERRORFLAG") else {
                continue;
            };
            let rest = &line[at..];
            let name = rest.split_whitespace().nth(2).expect("ERRORFLAG name");
            // Like upstream's `egrep -o '".*"'`: first quote to last quote.
            let (Some(a), Some(b)) = (rest.find('"'), rest.rfind('"')) else {
                panic!("ERRORFLAG without a message: {line}");
            };
            writeln!(flags, "#define {name} {n}").unwrap();
            writeln!(messages, "\t{},", &rest[a..=b]).unwrap();
            n += 1;
        }
    }
    writeln!(flags, "#define NERR {n}").unwrap();
    messages.push_str("\tNULL\n};\n");
    std::fs::write(out.join("errorflags.h"), flags).expect("write errorflags.h");
    std::fs::write(out.join("errormessages.h"), messages).expect("write errormessages.h");

    let mut build = cc::Build::new();
    for file in SOURCES {
        build.file(format!("{DIR}/{file}"));
    }
    // OUT_DIR first: the generated headers.
    build
        .include(&out)
        .include(DIR)
        // Upstream code; its warnings are not ours to fix.
        .warnings(false)
        .compile("texprintf");
    println!("cargo:rerun-if-changed={DIR}");
    println!("cargo:rerun-if-changed=build.rs");
}
