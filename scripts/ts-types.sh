#!/usr/bin/env bash
# Write crates/temzdf-script/ts-types/temzdf-all.d.ts (what `temzdf
# print-types` prints): the declarations written by hand (temzdf-core.d.ts,
# temzdf-actions.d.ts) and those of the modules scripts import
# (`temzdf/NAME`, the table MODULES in crates/temzdf-script/build.rs),
# bundled from their TypeScript by dts-bundle-generator, each in a
# `declare module "temzdf/NAME" { ... }` showing only what the module
# exports. scripts/check.sh checks that the committed file is what this
# writes. Re-executes itself inside the Nix dev shell when needed.
#
# Usage: scripts/ts-types.sh [OUT]   (default: the committed file)
#
# dts-bundle-generator and TypeScript 6 are devDependencies of
# crates/temzdf-script/runtime/package.json, found in $TEMZDF_NODE_MODULES.
# It keeps an import as it is only for a library, a module found in a
# node_modules directory: so `temzdf` (the declarations by hand) and the
# runtime are put under target/ts-types/node_modules/temzdf here, and
# `temzdf/NAME` resolves there, while the entries are read where they are
# (a library's files would be read as sources, not as declarations).
set -euo pipefail
self=$(realpath "${BASH_SOURCE[0]}")
cd "$(dirname "$(dirname "$self")")"

if [[ -z "${IN_NIX_SHELL:-}" ]]; then
  NIX_CONFIG="warn-dirty = false${NIX_CONFIG:+$'\n'$NIX_CONFIG}" exec nix develop --quiet -c "$self" "$@"
fi

types=crates/temzdf-script/ts-types
out=${1:-$types/temzdf-all.d.ts}
bundler=${TEMZDF_NODE_MODULES:?the dev shell sets it}/.bin/dts-bundle-generator
work=$PWD/target/ts-types
runtime=$PWD/crates/temzdf-script/runtime
rm -rf "$work"
mkdir -p "$work/node_modules/temzdf" "$work/out"

# The modules: ("NAME", "ENTRY") lines of build.rs's MODULES.
mapfile -t modules < <(sed -n '/^const MODULES/,/^];/s/^ *("\([^"]*\)", "\([^"]*\)"),$/\1 \2/p' \
  crates/temzdf-script/build.rs)
((${#modules[@]} > 0)) || { echo "no modules in crates/temzdf-script/build.rs" >&2; exit 1; }

# `temzdf` as a library: the bodies of the declarations' `declare module
# "temzdf"` blocks; what comes before the block (globals) stays global.
body() { sed -n '/^declare module "temzdf" {$/,/^}$/p' "$1" | sed '1d;$d'; }
{ body "$types/temzdf-core.d.ts"; body "$types/temzdf-actions.d.ts"; } >"$work/node_modules/temzdf/index.d.ts"
sed '/^declare module "temzdf" {$/,$d' "$types/temzdf-core.d.ts" >"$work/globals.d.ts"
ln -s "$runtime" "$work/node_modules/temzdf/runtime"
echo '{ "name": "temzdf", "version": "0.0.0", "types": "index.d.ts" }' >"$work/node_modules/temzdf/package.json"

paths='"temzdf": ["./node_modules/temzdf/index.d.ts"]'
files='"./globals.d.ts"'
entries=
for m in "${modules[@]}"; do
  name=${m%% *} entry=${m#* }
  paths+=", \"temzdf/$name\": [\"./node_modules/temzdf/runtime/$entry\"]"
  files+=", \"$runtime/$entry\""
  entries+="${entries:+,}
    { \"filePath\": \"$runtime/$entry\", \"outFile\": \"$work/out/${name//\//-}.d.ts\",
      \"output\": { \"exportReferencedTypes\": false, \"noBanner\": true },
      \"libraries\": { \"importedLibraries\": [\"temzdf\"] } }"
done
cat >"$work/tsconfig.json" <<EOF
{
  "compilerOptions": {
    "strict": true, "target": "es2022", "module": "esnext", "moduleResolution": "bundler",
    "allowImportingTsExtensions": true, "noEmit": true, "types": [], "lib": ["es2022"],
    "paths": { $paths }
  },
  "files": [$files]
}
EOF
cat >"$work/bundle.json" <<EOF
{
  "compilationOptions": { "preferredConfigPath": "$work/tsconfig.json" },
  "entries": [$entries
  ]
}
EOF
if ! "$bundler" --silent --config "$work/bundle.json" >"$work/bundle.log" 2>&1; then
  cat "$work/bundle.log" >&2
  exit 1
fi

# One `declare module` per module: inside one, declarations are ambient
# already (`declare` is an error there), and `export {}` is implied.
{
  echo "// Generated by scripts/ts-types.sh from $types/temzdf-core.d.ts,"
  echo "// $types/temzdf-actions.d.ts and the shipped modules (do not edit):"
  echo "// the scripting API of temzdf, as \`temzdf print-types\` prints it."
  echo
  cat "$types/temzdf-core.d.ts"
  echo
  cat "$types/temzdf-actions.d.ts"
  for m in "${modules[@]}"; do
    name=${m%% *}
    echo
    echo "declare module \"temzdf/$name\" {"
    grep -vx 'export {};' "$work/out/${name//\//-}.d.ts" | sed -E 's/^(export )?declare /\1/' | sed '/./,$!d'
    echo "}"
  done
} >"$out"
